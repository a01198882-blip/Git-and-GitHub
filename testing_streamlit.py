# This piece of code imports Streamlit to create the dashboard and Pandas to work with the data
import streamlit as st
import pandas as pd

# --------------------------------------------------
# Set up the page
# --------------------------------------------------

# This piece of code configures the title, icon, and layout of the dashboard
st.set_page_config(
    page_title="Sellers Dashboard",
    page_icon="📊",
    layout="wide"
)

# --------------------------------------------------
# Load the dataset
# --------------------------------------------------

# This piece of code reads the Excel file that contains the sellers information
# Cache the data so it does not have to be loaded every time
@st.cache_data
def load_data():
    data = pd.read_excel("sellers.xlsx")
    return data

# This piece of code stores the dataset in a variable
df = load_data()

# This piece of code combines the first name and last name to create a full name
df["FULL NAME"] = df["NAME"] + " " + df["LASTNAME"]

# --------------------------------------------------
# Add the dashboard title and introduction
# --------------------------------------------------

# This piece of code displays the main title of the application
st.title("📊 Sellers Dashboard")

# This piece of code adds a short description explaining the purpose of the dashboard
st.write(
    "This dashboard allows users to analyze seller performance "
    "by region and visualize important sales indicators."
)

# --------------------------------------------------
# Create the region filter
# --------------------------------------------------

# This piece of code adds a title to the sidebar where the filters will be located
st.sidebar.header("Dashboard Filters")

# This piece of code gets all the different regions available in the dataset
regions = sorted(df["REGION"].unique())

# This piece of code allows the user to select one or more regions
selected_regions = st.sidebar.multiselect(
    "Select Region:",
    options=regions,
    default=regions
)

# This piece of code keeps only the sellers that belong to the selected regions
filtered_df = df[df["REGION"].isin(selected_regions)]

# --------------------------------------------------
# Show the sellers table
# --------------------------------------------------

# This piece of code adds a heading for the table
st.header("Seller Information")

# This piece of code uses a container to organize the table
with st.container():

    # This piece of code displays the seller information based on the selected regions
    st.dataframe(
        filtered_df[
            [
                "REGION",
                "ID",
                "NAME",
                "LASTNAME",
                "INCOME",
                "SOLD UNITS",
                "TOTAL SALES",
                "SALES AVERAGE"
            ]
        ],
        use_container_width=True,
        hide_index=True
    )

    # This piece of code hows the number of sellers included in the table
    st.caption(
        f"Number of sellers displayed: {len(filtered_df)}"
    )

# --------------------------------------------------
# Calculate and display the main indicators
# --------------------------------------------------

# This piece of code calculates the total number of units sold by the selected sellers
total_units = filtered_df["SOLD UNITS"].sum()

# This piece of code calculates the total sales generated by the selected sellers
total_sales = filtered_df["TOTAL SALES"].sum()

# This piece of code calculates the average sales value of the selected sellers
average_sales = filtered_df["SALES AVERAGE"].mean()

# This piece of code creates three columns to display the indicators next to each other
col1, col2, col3 = st.columns(3)

# This piece of code displays the total units sold
with col1:
    st.metric(
        label="Total Units Sold",
        value=f"{total_units:,}"
    )

# This piece of code displays the total sales
with col2:
    st.metric(
        label="Total Sales",
        value=f"{total_sales:,}"
    )

# This piece of code displays the average sales
with col3:
    st.metric(
        label="Average Sales",
        value=f"{average_sales:.4f}"
    )

# --------------------------------------------------
# Organize the data for the regional graphs
# --------------------------------------------------

# This piece of code groups the sellers by region and add up their units sold
units_by_region = (
    filtered_df.groupby("REGION")["SOLD UNITS"]
    .sum()
    .reset_index()
)

# This piece of code groups the sellers by region and calculate their total sales
sales_by_region = (
    filtered_df.groupby("REGION")["TOTAL SALES"]
    .sum()
    .reset_index()
)

# This piece of code groups the sellers by region and calculate the average sales
average_by_region = (
    filtered_df.groupby("REGION")["SALES AVERAGE"]
    .mean()
    .reset_index()
)

# --------------------------------------------------
# Create the Units Sold graph
# --------------------------------------------------

# This piece of code adds a heading for the first graph
st.header("Units Sold by Region")

# This piece of code uses a container to organize the visualization
with st.container():

    # Create a bar chart to compare the units sold in each region
    st.bar_chart(
        data=units_by_region,
        x="REGION",
        y="SOLD UNITS",
        use_container_width=True
    )

# --------------------------------------------------
# Create the Total Sales graph
# --------------------------------------------------

# This piece of code adds a heading for the second graph
st.header("Total Sales by Region")

with st.container():

    # Create a bar chart to compare total sales between regions
    st.bar_chart(
        data=sales_by_region,
        x="REGION",
        y="TOTAL SALES",
        use_container_width=True
    )

# --------------------------------------------------
# Create the Average Sales graph
# --------------------------------------------------

# This piece of code adds a heading for the third graph
st.header("Average Sales by Region")

with st.container():

    # This piece of code creates a bar chart to compare average sales between regions
    st.bar_chart(
        data=average_by_region,
        x="REGION",
        y="SALES AVERAGE",
        use_container_width=True
    )

# --------------------------------------------------
# Show the information of a specific vendor
# --------------------------------------------------

# This piece of code adds a heading for the individual seller section
st.header("Individual Vendor Analysis")

# This piece of code checks if there are sellers available after applying the region filter
if not filtered_df.empty:

    # This piece of code creates a list containing each seller's ID and full name
    vendor_options = filtered_df.apply(
        lambda row: f"{row['ID']} - {row['FULL NAME']}",
        axis=1
    ).tolist()

    # This piece of code lets the user choose which seller they want to analyze
    selected_vendor = st.selectbox(
        "Select a Vendor:",
        options=vendor_options
    )

    # This piece of code gets the ID of the seller selected by the user
    selected_vendor_id = int(selected_vendor.split(" - ")[0])

    # This piece of code finds the row that contains the selected seller's information
    vendor_data = filtered_df[
        filtered_df["ID"] == selected_vendor_id
    ].iloc[0]

    # This piece of code displays the seller's information inside a container
    with st.container():

        # This piece of code shows the seller's full name
        st.subheader(vendor_data["FULL NAME"])

        # This piece of code creates two columns to organize the seller's information
        vendor_col1, vendor_col2 = st.columns(2)

        # This piece of code displays general information about the seller
        with vendor_col1:

            st.write("**Region:**", vendor_data["REGION"])

            st.write("**Vendor ID:**", vendor_data["ID"])

            st.write("**Income:**", f"{vendor_data['INCOME']:,}")

        # This piece of code displays the seller's sales indicators
        with vendor_col2:

            st.metric(
                label="Units Sold",
                value=f"{vendor_data['SOLD UNITS']:,}"
            )

            st.metric(
                label="Total Sales",
                value=f"{vendor_data['TOTAL SALES']:,}"
            )

            st.metric(
                label="Average Sales",
                value=f"{vendor_data['SALES AVERAGE']:.4f}"
            )

        # This piece of code adds a heading for the seller's individual graph
        st.subheader("Vendor Sales Performance")

        # This piece of code creates a small table with the selected seller's sales indicators
        vendor_chart_data = pd.DataFrame({
            "Indicator": [
                "Units Sold",
                "Total Sales",
                "Average Sales"
            ],
            "Value": [
                vendor_data["SOLD UNITS"],
                vendor_data["TOTAL SALES"],
                vendor_data["SALES AVERAGE"]
            ]
        })

        # This piece of code displays a bar chart with the seller's individual performance
        st.bar_chart(
            data=vendor_chart_data,
            x="Indicator",
            y="Value",
            use_container_width=True
        )

# This piece of code shows a message if the user has not selected any region
else:

    st.warning(
        "Please select at least one region to display vendor information."
    )
